void main() {
  var a = 10;
  var b = 3;

  print("++a: " + (++a).toString());
  print("a: " + a.toString());

  print("b++: " + (b++).toString());
  print("b: " + b.toString());

  var c = 10;
  var d = 3;

  print("--c: " + (--c).toString());
  print("c: " + c.toString());

  print("d--: " + (d--).toString());
  print("d: " + d.toString());
}
