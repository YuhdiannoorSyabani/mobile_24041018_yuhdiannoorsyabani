void main() {
  var sum = 10 + 3;
  print("Penjumlahan: 10 + 3 = $sum");

  var difference = 10 - 3;
  print("Pengurangan: 10 - 3 = $difference");

  var Negative = -10;
  print("Negatif: 3 - 10 = $Negative");

  var Positive = 10;
  print("Positif: 10 = $Positive");

  var product = 10 * 3;
  print("Perkalian: 10 * 3 = $product");

  var quotient = 10 / 3;
  print("Pembagian: 10 / 3 = $quotient");

  var integerDivision = 10 ~/ 3;
  print("Pembagian Integer: 10 ~/ 3 = $integerDivision");

  var remainder = 10 % 3;
  print("Modulus: 10 % 3 = $remainder");
}
