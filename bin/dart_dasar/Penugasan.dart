void main() {
  // assignment operator
  var VaInit = 20;
  var Vadou = 10;

  VaInit += 5;
  print("Nilai a setelah a += 5: $VaInit");

  VaInit -= 3;
  print("Nilai a setelah a -= 3: $VaInit");

  VaInit *= 2;
  print("Nilai a setelah a *= 2: $VaInit");

  VaInit ~/= 10;
  print("Nilai a setelah a ~/= 10: $VaInit");

  Vadou %= 3;
  print("Nilai b setelah b %= 3: $Vadou");
}
